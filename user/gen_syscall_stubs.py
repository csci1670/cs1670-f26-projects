#!/usr/bin/python3

# Generate syscalls.S, the user-side stubs for the system calls, from the
# system call numbers that kernel/syscall.h defines: every line of the form
#
#   #define SYS_<name> <number>
#
# becomes an assembly function called <name> that executes `svc #<number>`
# and returns. Because our system call ABI passes arguments and the result
# in the same registers as an ordinary C function call (x0-x5, and x0), that
# is all a stub needs to do.
#
# Note that you separately have to declare each system call in
# user/lib/u_syscalls.h to give it a C API.

import re
import sys

DEFINE = re.compile(r"#define\s+SYS_(\w+)\s+\(?\s*(\w+)\s*\)?")


def stub(name, number):
    print(f"  .global {name}")
    print(f"  .type {name}, %function")
    print(f"{name}:")
    print(f"  svc #{number}")
    print("  ret")
    print(f"  .size {name}, . - {name}")
    print()


def main():
    print("// generated by gen_syscall_stubs.py from kernel/syscall.h; do not edit")
    print()
    print("  .section .text")
    print()

    with open("kernel/syscall.h") as f:
        for line in f:
            if not line.startswith("#define SYS_"):
                continue
            m = DEFINE.match(line)
            if m is None:
                sys.exit(f"gen_syscall_stubs.py: cannot parse: {line.strip()}")
            name, number = m.group(1), m.group(2)
            try:
                value = int(number, 0)
            except ValueError:
                sys.exit(f"gen_syscall_stubs.py: SYS_{name} must be a number, not '{number}'")
            if not 0 <= value <= 0xFFFF:
                sys.exit(f"gen_syscall_stubs.py: SYS_{name} = {value} does not fit in svc's 16-bit immediate")
            stub(name, value)


if __name__ == "__main__":
    main()
